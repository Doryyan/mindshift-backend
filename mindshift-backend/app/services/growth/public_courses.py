    """Get all available public courses (with summaries only)."""
    return [
        {
            "topic": c["topic"],
            "title": c["title"],
            "subtitle": c["subtitle"],
            "key_takeaway": c["key_takeaway"],
            "week_number": c["week_number"],
            "sections_count": len(c["sections"]),
        }
        for c in COURSES
    ]
