def get_course_by_topic(topic: str) -> dict | None:
    """Get a pre-defined course by topic identifier."""
    for course in COURSES:
        if course["topic"] == topic:
            return course
    return None


def get_current_week_course() -> dict:
    """Get this week's course based on rotation (4-week cycle)."""
    now = datetime.now(timezone.utc)
    # Use ISO week number to determine which course to show
    week_number = now.isocalendar()[1] % 4
    # Map to course index (0-3)
    course_index = week_number if week_number < 4 else 0
    return COURSES[course_index % len(COURSES)]


